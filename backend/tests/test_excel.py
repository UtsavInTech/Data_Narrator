"""The Excel reader against the kind of workbook companies actually send around."""
import datetime as dt

import pytest
from openpyxl import Workbook
from openpyxl.worksheet.table import Table

from datanarrator.connectors.excel import parse_workbook


@pytest.fixture(scope="module")
def messy_workbook(tmp_path_factory):
    wb = Workbook()

    # 1. Report-style sheet: merged title, subtitle, grouped regions, subtotals, text numbers, errors.
    ws = wb.active
    ws.title = "Report"
    ws["A1"] = "ACME Corp - Regional Sales FY24"
    ws.merge_cells("A1:E1")
    ws["A2"] = "Generated by ERP export"
    ws.append([])
    ws.append(["Region", "Product", "Units", "Revenue", "Profit"])
    rows = [
        ["North", "Chairs", 10, "₹1,200", "(150)"],
        [None, "Tables", 5, "₹2,500", "300"],
        ["Subtotal", None, 15, "₹3,700", "150"],
        ["South", "Chairs", 7, "₹840", "#N/A"],
        [None, "Tables", 9, "₹4,500", "900"],
        [None, "Lamps", 20, "₹1,000", "250"],
        ["Subtotal", None, 36, "₹6,340", "1,150"],
        ["Grand Total", None, 51, "₹10,040", "1,300"],
    ]
    for r in rows:
        ws.append(r)

    # 2. Months as columns (real dates in the header) + a Total column.
    ws = wb.create_sheet("Monthly")
    ws.append(["Product"] + [dt.datetime(2024, m, 1) for m in range(1, 13)] + ["Total"])
    for p, base in (("Chairs", 100), ("Tables", 200), ("Lamps", 50)):
        vals = [base + m * 10 for m in range(12)]
        ws.append([p] + vals + [sum(vals)])

    # 3. Same layout on three monthly sheets -> stacked.
    for month in ("Jan", "Feb", "Mar"):
        ws = wb.create_sheet(month)
        ws.append(["Store", "Sales", "Visitors"])
        for s, v in (("Delhi", 100), ("Pune", 80), ("Kochi", 60)):
            ws.append([s, v, v * 3])

    # 4. Two titled tables side by side.
    ws = wb.create_sheet("Two tables")
    ws["A1"], ws["F1"] = "Employees", "Departments"
    ws.append([])
    ws.append(["Emp ID", "Name", "Dept", None, None, "Dept", "Head"])
    for i, (n, d) in enumerate([("Asha", "HR"), ("Ravi", "IT"), ("Meera", "IT")], start=1):
        ws.append([f"E{i}", n, d])
    ws["F4"], ws["G4"], ws["F5"], ws["G5"] = "HR", "Kiran", "IT", "Sunil"

    # 5. Two-row header with merged group labels.
    ws = wb.create_sheet("Plan vs Actual")
    ws.append(["Region", "Q1", None, "Q2", None])
    ws.append([None, "Plan", "Actual", "Plan", "Actual"])
    ws.merge_cells("A1:A2")
    ws.merge_cells("B1:C1")
    ws.merge_cells("D1:E1")
    ws.append(["North", 100, 90, 120, 130])
    ws.append(["South", 80, 85, 90, 70])

    # 6. A defined Excel Table, with junk notes elsewhere on the sheet.
    ws = wb.create_sheet("Defined")
    ws["A1"] = "Notes: do not edit"
    ws.append([])
    ws.append(["SKU", "Price", "Stock"])
    ws.append(["A-1", 9.5, 100])
    ws.append(["A-2", 12.0, 0])
    ws.add_table(Table(displayName="Inventory", ref="A3:C5"))

    path = tmp_path_factory.mktemp("xl") / "messy.xlsx"
    wb.save(path)
    return {t.name: t for t in parse_workbook(path)}


def test_report_sheet_title_totals_and_grouping(messy_workbook):
    t = messy_workbook["ACME Corp - Regional Sales FY24"]
    df = t.frame
    assert list(df.columns) == ["Region", "Product", "Units", "Revenue", "Profit"]
    assert len(df) == 5, "subtotal and grand total rows must be removed"
    assert df["Region"].tolist() == ["North", "North", "South", "South", "South"], "groups filled down"
    assert df["Profit"].isna().sum() == 1, "#N/A becomes empty"
    notes = " ".join(t.report["notes"])
    assert "total" in notes and "filled down" in notes and "error" in notes
    assert t.report["header_row"] == 4


def test_months_as_columns_are_unpivoted(messy_workbook):
    df = messy_workbook["Monthly"].frame
    assert list(df.columns) == ["Product", "Period", "Value"]
    assert len(df) == 36 and "Total" not in df.columns
    assert df["Period"].iloc[0] == "Jan 2024"


def test_identical_sheets_are_stacked(messy_workbook):
    t = messy_workbook["Jan + 2 more"]
    assert len(t.frame) == 9
    assert sorted(t.frame["Sheet"].unique()) == ["Feb", "Jan", "Mar"]


def test_side_by_side_tables_with_titles(messy_workbook):
    emp, dept = messy_workbook["Employees"], messy_workbook["Departments"]
    assert list(emp.frame.columns) == ["Emp ID", "Name", "Dept"] and len(emp.frame) == 3
    assert list(dept.frame.columns) == ["Dept", "Head"] and len(dept.frame) == 2


def test_two_row_header(messy_workbook):
    df = messy_workbook["Plan vs Actual"].frame
    assert list(df.columns) == ["Region", "Q1 - Plan", "Q1 - Actual", "Q2 - Plan", "Q2 - Actual"]
    assert len(df) == 2


def test_defined_excel_table(messy_workbook):
    df = messy_workbook["Inventory"].frame
    assert list(df.columns) == ["SKU", "Price", "Stock"] and len(df) == 2


def test_fill_down_with_sparse_other_column(tmp_path):
    """Group labels are filled down even when another column is mostly '-'."""
    wb = Workbook()
    ws = wb.active
    ws.append(["Branch", "Line", "Units", "Returns"])
    for b in ("Delhi", "Pune"):
        for i, line in enumerate(("A", "B", "C")):
            ws.append([b if i == 0 else None, line, 10 + i, "-" if i else 2])
    path = tmp_path / "sparse.xlsx"
    wb.save(path)
    df = parse_workbook(path)[0].frame
    assert df["Branch"].tolist() == ["Delhi"] * 3 + ["Pune"] * 3
